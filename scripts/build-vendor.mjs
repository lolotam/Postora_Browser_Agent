// Bundles the pi-ai OAuth flows into src/vendor/pi-oauth.js, the only
// build step of this extension. The output is committed, so the extension
// loads unpacked from the repository with nothing else to run.
//
//   npm run build:vendor

import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PI_AI_DIR = path.join(ROOT, 'node_modules/@earendil-works/pi-ai');
const OAUTH_DIR = path.join(PI_AI_DIR, 'dist/auth/oauth');
const STUB = path.join(ROOT, 'scripts/vendor-node-stub.js');
const OUT_FILE = path.join(ROOT, 'src/vendor/pi-oauth.js');

// pi-ai's exports map hides dist/auth/*, so the flows are imported by their
// resolved path. Each file exports one OAuth flow object.
const FLOWS = [
  { file: 'anthropic.js', export: 'anthropicOAuth' },
  { file: 'openai-codex.js', export: 'openaiCodexOAuth' },
  { file: 'xai.js', export: 'xaiOAuth' },
  { file: 'kimi-coding.js', export: 'kimiCodingOAuth' },
];

/** Pin Kimi's authority and reject token-bearing redirects in the browser build. */
export function kimiBrowserSource(source) {
  const host = /function getOauthHost\(\) \{[\s\S]*?\n\}/;
  const requests = source.match(/signal: requestSignal\(signal\),/g) ?? [];
  if (!host.test(source) || requests.length !== 3) throw new Error('Review the updated pi Kimi OAuth source before bundling it');
  return source.replace(host, 'function getOauthHost() { return DEFAULT_OAUTH_HOST; }')
    .replaceAll('signal: requestSignal(signal),', 'redirect: "error", signal: requestSignal(signal),');
}

/** The banner every build of the bundle carries. */
export function banner() {
  const { name, version, license } = JSON.parse(fs.readFileSync(path.join(PI_AI_DIR, 'package.json'), 'utf8'));
  return [
    `// ${name} ${version} — ${license} licence.`,
    '// The OAuth login and refresh flows of pi-ai, bundled for the browser.',
    '// Generated by `npm run build:vendor` — do not edit.',
  ].join('\n');
}

/**
 * The esbuild options that produce the bundle. `absWorkingDir` and relative
 * paths keep the output free of absolute paths, so two builds on two machines
 * give the same bytes.
 */
export function buildOptions() {
  return {
    absWorkingDir: ROOT,
    stdin: {
      contents: FLOWS.map((f) => `export { ${f.export} } from './${f.file}';`).join('\n'),
      resolveDir: OAUTH_DIR,
      sourcefile: 'pi-oauth.js',
      loader: 'js',
    },
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['chrome116'],
    alias: { 'node:http': STUB, 'node:crypto': STUB, 'node:fs': STUB },
    banner: { js: banner() },
    legalComments: 'none',
    plugins: [{
      name: 'kimi-browser-boundary',
      setup(build) {
        build.onLoad({ filter: /[\\/]auth[\\/]oauth[\\/]kimi-coding\.js$/ }, (args) => ({
          contents: kimiBrowserSource(fs.readFileSync(args.path, 'utf8')), loader: 'js',
        }));
      },
    }],
    outfile: OUT_FILE,
    logLevel: 'warning',
  };
}

/** The bundle as a string, without writing it anywhere. */
export async function buildBundle() {
  const result = await esbuild.build({ ...buildOptions(), write: false });
  const file = result.outputFiles?.find((f) => f.path.endsWith('pi-oauth.js'));
  if (!file) throw new Error('esbuild produced no bundle for src/vendor/pi-oauth.js');
  return file.text;
}

async function main() {
  const code = await buildBundle();
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, code);
  console.log(`src/vendor/pi-oauth.js: ${(code.length / 1024).toFixed(0)} KB`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
